import fs from 'fs/promises';
import path from 'path';

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) {
      const key = argv[i].slice(2);
      const next = argv[i + 1];
      if (next && !next.startsWith('--')) {
        args[key] = next;
        i++;
      } else {
        args[key] = true;
      }
    }
  }
  return args;
}

async function generateTeamsFile() {
  try {
    const args = parseArgs(process.argv.slice(2));
    const year = args.year || String(new Date().getFullYear());
    const startStr = args.start || `${year}-03-18`;
    const endStr = args.end || `${year}-03-23`;
    const outRel = args.out || `src/data/seasons/${year}.teams.js`;

    const startDate = new Date(startStr);
    const endDate = new Date(endStr);
    let teams = new Map();

    console.log(`Fetching ${year} NCAA tournament teams from ESPN (${startStr} to ${endStr})...`);

    for (let d = new Date(startDate); d <= endDate; d.setDate(d.getDate() + 1)) {
      const dateStr = d.toISOString().split('T')[0].replace(/-/g, '');
      const url = `https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball/scoreboard?dates=${dateStr}&limit=100`;
      const res = await fetch(url);
      const data = await res.json();

      if (data.events) {
        data.events.forEach(event => {
          const notesText = event.competitions?.[0]?.notes?.map(n => n.headline).join(" ") || "";
          const isNCAA = notesText.includes("NCAA");
          const isFirstFour = notesText.includes("First Four");

          // Ensure it's an NCAA Tournament Round of 64/32 game (exclude NIT and First Four)
          if (event.season?.type === 3 && isNCAA && !isFirstFour) {
            const comps = event.competitions[0].competitors;
            comps.forEach(c => {
              if (!teams.has(c.team.id)) {
                teams.set(c.team.id, {
                  id: teams.size + 1,
                  name: c.team.displayName,
                  espnId: c.team.id,
                  logo: c.team.logo || null,
                  seed: c.curatedRank?.current || null,
                  wins: 0,
                  losses: 0,
                  eliminated: false
                });
              }
            });
          }
        });
      }
    }

    console.log(`Found ${teams.size} unique tournament teams.`);

    if (teams.size === 64) {
      const teamsArray = Array.from(teams.values());

      // Sort alphabetically for clean output
      teamsArray.sort((a, b) => a.name.localeCompare(b.name));

      // Re-assign IDs 1-64 based on alphabetical order for cleanliness
      teamsArray.forEach((t, i) => { t.id = i + 1; });

      const fileContent = `// This file was auto-generated by scripts/fetchTeams.js
// It contains the 64 tournament teams for the ${year} March Madness pool.

export const teams = ${JSON.stringify(teamsArray, null, 2)};
`;

      const outputPath = path.resolve(process.cwd(), outRel);
      await fs.writeFile(outputPath, fileContent, 'utf-8');
      console.log(`Successfully generated ${outputPath}`);
    } else {
      console.error(`Error: Found ${teams.size} teams instead of exactly 64. Aborting file creation.`);
      process.exitCode = 1;
    }
  } catch (e) {
    console.error("Error generating teams file:", e);
    process.exitCode = 1;
  }
}

generateTeamsFile();
